import { cookies } from "next/headers";
import { getWorkspaceLocale } from "@/lib/data-store";

export type AppLocale = "en" | "zh" | "es";

export function normalizeLocale(value: unknown): AppLocale {
  return value === "zh" || value === "es" ? value : "en";
}

export async function getLocale(): Promise<AppLocale> {
  const store = await cookies();
  const cookieLocale = store.get("rankcues_locale")?.value;
  if (cookieLocale) return normalizeLocale(cookieLocale);
  try {
    return normalizeLocale(await getWorkspaceLocale());
  } catch {
    return "en";
  }
}

export function pick(locale: AppLocale, en: string, zh: string, es: string) {
  return locale === "zh" ? zh : locale === "es" ? es : en;
}

